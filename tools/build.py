def sec(id_, title, body):
    return f'<section class="art-sec" id="{id_}"><div class="h2wrap"><h2>{title}</h2></div>\n{body}\n</section>'


def table(head_cols, rows):
    th = "".join(f"<th scope=\"col\">{c}</th>" for c in head_cols)
    tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="tbl-wrap"><table class="tbl"><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>'


def steps(items):
    return '<ol class="steps">' + "".join(f"<li><b>{t}</b>{b}</li>" for t, b in items) + "</ol>"


def faq_html(items):
    return "".join(f'<details class="faq"><summary>{q}</summary><div class="a">{a}</div></details>' for q, a in items)


def faq_ld(items):
    return {"@context": "https://schema.org", "@type": "FAQPage",
            "mainEntity": [{"@type": "Question", "name": strip_tags(q),
                            "acceptedAnswer": {"@type": "Answer", "text": strip_tags(a)}} for q, a in items]}


def crumb_ld(file, name):
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "ホーム", "item": BASE_URL},
        {"@type": "ListItem", "position": 2, "name": name, "item": url_of(file)}]}


